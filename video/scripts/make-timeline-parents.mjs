// Builds src/parents/timeline.ts from scripts/parents-shots.json.
//
// Unlike the pension and student-loan Shorts, this one is NOT cut to a
// voiceover: no recording exists yet. The pack's designed timecodes are the
// timeline, and they are usable here where they were not there — the pack's
// 130 events are continuous, gapless and resolve to exactly 29:45, which
// parse-parents-pack.mjs checks on every build. When the read is delivered,
// re-time against it with force-align.py exactly as the Shorts do; nothing
// downstream of this file assumes the pack's numbers are final.
import {readFileSync, writeFileSync, mkdirSync, existsSync} from 'node:fs';

const FPS = 30;
const here = (p) => new URL(p, import.meta.url).pathname;
const shots = JSON.parse(readFileSync(here('./parents-shots.json'), 'utf8'));

// Section 03 of the pack. The Arabic is taken from the CSV rather than retyped
// — retyping Quranic text to paste it into a build script is the exact error
// the pack calls its highest-risk item — so only the transliteration and the
// meaning line live here, keyed by card id.
const CARD_TEXT = {
  C1: ['WA-QADA RABBUKA', 'And your Lord has decreed'],
  C2: ['WA BIL-WALIDAYNI IHSANA', 'and to parents, good treatment'],
  C3: ["WAHNAN 'ALA WAHN", 'weakness upon weakness'],
  C4: ['WA LI-WALIDAYKA', '...and to your parents'],
  C5: ['UFF', 'a breath of irritation'],
  C6: ['QAWLAN KARIMA', 'a noble word'],
  C7: ["BIRR / 'UQUQ", 'expansive goodness / the cut'],
  C8: ["WA SAHIBHUMA MA'RUFA", 'and keep company with them with kindness'],
  C9: ['RABBI-RHAMHUMA KAMA RABBAYANI SAGHIRA', 'as they raised me when I was small'],
};

// The move each event makes across its still. Stills get a slow push; re-frames
// get the move the pack wrote for them, read off the CSV's prose rather than
// assigned by hand so the two cannot disagree.
//
// The pack's ceiling is ~4% of frame width per second. That is a cap on speed,
// not a target: at 4%/s a 15s shot would travel 60% of the frame. Every move
// here is a fixed total travel, which puts the fastest of them an order of
// magnitude inside the cap.
const move = (shot) => {
  if (shot.kind !== 'reframe') return {kind: 'push', from: 1.0, to: 1.06};
  const p = shot.prompt.toLowerCase();
  if (/widen|pull back/.test(p)) return {kind: 'widen', from: 1.34, to: 1.0};
  if (/lateral (pan|drift)/.test(p)) return {kind: 'lateral', from: 1.14, to: 1.14};
  if (/hold on|hold and/.test(p)) return {kind: 'hold', from: 1.06, to: 1.12};
  return {kind: 'push', from: 1.06, to: 1.4};   // "push to/in on <detail>"
};

const CHAPTERS = new Map();
for (const s of shots) if (!CHAPTERS.has(s.chapter)) CHAPTERS.set(s.chapter, s.start);

// A re-frame draws on its parent's still. The CSV fills in `asset` for some of
// them and leaves it empty for others, so it is resolved from the parent here —
// otherwise a re-frame of an un-generated shot reports itself as having artwork.
const assetOf = new Map(shots.map((s) => [s.id, s.asset]));
const resolve = (s, seen = new Set()) => {
  if (s.kind === 'card') return null;
  if (assetOf.get(s.id)) return assetOf.get(s.id);
  if (!s.rfParent || seen.has(s.id)) return null;
  seen.add(s.id);
  const parent = shots.find((x) => x.id === s.rfParent);
  return parent ? resolve(parent, seen) : null;
};

const events = shots.map((s) => {
  const asset = resolve(s);
  const present = asset ? existsSync(here(`../public/parents/${asset}`)) : true;
  const m = move(s);
  return {
    id: s.id,
    kind: s.kind,
    chapter: s.chapter,
    from: Math.round(s.start * FPS),
    durationInFrames: Math.round(s.end * FPS) - Math.round(s.start * FPS),
    asset,
    present,
    parent: s.rfParent,
    move: m.kind,
    scaleFrom: m.from,
    scaleTo: m.to,
    // Cards carry their own three lines; shots carry the prompt so the studio
    // sidebar names what you are looking at.
    arabic: s.kind === 'card' ? s.prompt.replace(/[★\[].*$/u, '').trim() : '',
    translit: s.kind === 'card' ? CARD_TEXT[s.id][0] : '',
    meaning: s.kind === 'card' ? CARD_TEXT[s.id][1] : '',
    split: s.id === 'C7',
    note: s.kind === 'card' ? '' : s.prompt.slice(0, 120),
  };
});

for (const c of events.filter((e) => e.kind === 'card'))
  if (!c.arabic || !c.translit) throw new Error(`card ${c.id} is missing text`);

const totalFrames = events.at(-1).from + events.at(-1).durationInFrames;

mkdirSync(here('../src/parents/'), {recursive: true});
writeFileSync(here('../src/parents/timeline.ts'),
`// GENERATED by scripts/make-timeline-parents.mjs — do not edit by hand.
// Timings are the scene pack's own designed timecodes (clarity/parents-timeline.csv),
// not a forced alignment: the voiceover for this film has not been recorded yet.
export type Event = {
  id: string; kind: 'still' | 'reframe' | 'card'; chapter: string;
  from: number; durationInFrames: number; asset: string | null; present: boolean;
  parent: string | null; move: string; scaleFrom: number; scaleTo: number;
  arabic: string; translit: string; meaning: string; split: boolean; note: string;
};

export const FPS = ${FPS};
export const TOTAL_FRAMES = ${totalFrames};
export const EVENTS: Event[] = ${JSON.stringify(events, null, 2)};
`);

const missing = events.filter((e) => !e.present);
const secs = totalFrames / FPS;
console.log(`${events.length} events, ${totalFrames} frames (${Math.floor(secs / 60)}:${String(secs % 60).padStart(2, '0')})`);
console.log(`moves: ` + Object.entries(events.reduce((a, e) => ((a[e.move] = (a[e.move] || 0) + 1), a), {}))
  .map(([k, v]) => `${k} ${v}`).join('  '));
if (missing.length) {
  const stills = [...new Set(missing.filter((m) => m.kind === 'still').map((m) => m.id))];
  console.log(`\n${missing.length} events have no artwork on disk (${stills.length} un-generated stills,`);
  console.log(`  ${missing.length - stills.length} re-frames of them): ${missing.map((m) => m.id).join(' ')}`);
  console.log('  They render as a slate carrying the shot id and its prompt, so the cut');
  console.log('  stays whole and the holes are visible rather than silent.');
}
