// Assembles the Short's voiceover out of the supplied long-form read.
//
// Every gap — the pad either side of a span, the tightened join between two spans
// of one frame, and the rest held after a frame — is filled with ROOM TONE lifted
// from the source's own longest pause, not with digital silence. Cutting sentences
// out of a continuous read and butting them against true silence is audible; the
// tone floor dropping out mid-film is the tell. This keeps one continuous floor.
//
// Emits:  media/klarna-vo.m4a          the cut narration
//         video/src/klarna/timing.ts   frame-exact spans for the composition
//
// Usage: node scripts/build-klarna-vo.mjs /path/to/source.mov

import {execFileSync} from 'node:child_process';
import {mkdirSync, writeFileSync, rmSync, copyFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';
import {EDIT, PAD_IN, PAD_OUT, speechOf, spanOf, totalSeconds} from './klarna-edit.mjs';

const require = createRequire(import.meta.url);
const SRC = process.argv[2];
if (!SRC) throw new Error('usage: build-klarna-vo.mjs <source.mov>');

// ffmpeg comes from the imageio wheel; this box has no system ffmpeg.
const FF = execFileSync('python3', ['-c', 'import imageio_ffmpeg;print(imageio_ffmpeg.get_ffmpeg_exe())'])
  .toString().trim();

const FPS = 30;
const TMP = path.resolve('.klarna-vo');
rmSync(TMP, {recursive: true, force: true});
mkdirSync(TMP, {recursive: true});

const ff = (args) => execFileSync(FF, ['-hide_banner', '-loglevel', 'error', ...args]);

// Room tone: the source's longest pause is 10.56 → 12.39. Take its clean middle.
const TONE = path.join(TMP, 'tone.wav');
ff(['-ss', '10.75', '-t', '1.45', '-i', SRC, '-map', '0:a', '-ac', '2', '-ar', '48000',
    '-af', 'afade=t=in:d=0.05,afade=t=out:st=1.40:d=0.05', TONE, '-y']);

/** A run of room tone of exactly `d` seconds, looped from TONE. */
let toneN = 0;
const tone = (d) => {
  const out = path.join(TMP, `tone${toneN++}.wav`);
  ff(['-stream_loop', '-1', '-i', TONE, '-t', d.toFixed(4), '-ac', '2', '-ar', '48000', out, '-y']);
  return out;
};

/** One spoken span, with short fades so the cut edge is not a click. */
let spanN = 0;
const span = ([a, b]) => {
  const d = b - a;
  const out = path.join(TMP, `sp${spanN++}.wav`);
  ff(['-ss', a.toFixed(4), '-t', d.toFixed(4), '-i', SRC, '-map', '0:a', '-ac', '2', '-ar', '48000',
      '-af', `afade=t=in:d=0.025,afade=t=out:st=${Math.max(0, d - 0.025).toFixed(4)}:d=0.025`,
      out, '-y']);
  return out;
};

const parts = [];
const timing = [];
let cursor = 0;

for (const e of EDIT) {
  const startS = cursor;
  parts.push(tone(PAD_IN));
  e.vo.forEach((v, i) => {
    if (i) parts.push(tone(e.join ?? 0.26));
    parts.push(span(v));
  });
  parts.push(tone(PAD_OUT + e.gap));
  cursor += spanOf(e);
  timing.push({
    id: e.id,
    still: e.still,
    from: Math.round(startS * FPS),
    durationInFrames: Math.round(cursor * FPS) - Math.round(startS * FPS),
    speech: [Math.round((startS + PAD_IN) * FPS), Math.round((startS + PAD_IN + speechOf(e)) * FPS)],
    move: e.move,
    cold: !!e.cold,
    figureY: e.figureY ?? 780,
    cap: e.cap,
    num: e.num,
  });
}

// Concat, then a single gentle loudness pass so the re-cut sits where the channel's
// other uploads sit. -14 LUFS is YouTube's normalisation target; going louder just
// gets turned back down, and going quieter loses against everything around it.
const list = path.join(TMP, 'list.txt');
writeFileSync(list, parts.map((p) => `file '${p}'`).join('\n'));
mkdirSync(path.resolve('../media'), {recursive: true});
const OUT = path.resolve('../media/klarna-vo.m4a');
// loudnorm resamples to 192k/96k internally; pin the output back to 48 kHz.
ff(['-f', 'concat', '-safe', '0', '-i', list,
    '-af', 'loudnorm=I=-14:TP=-1.5:LRA=11,aresample=48000',
    '-ar', '48000', '-c:a', 'aac', '-b:a', '192k', OUT, '-y']);

// The composition loads it through staticFile(), so it also has to live in public/.
copyFileSync(OUT, path.resolve('public/klarna-vo.m4a'));

const total = totalSeconds();
const totalFrames = timing.at(-1).from + timing.at(-1).durationInFrames;

mkdirSync(path.resolve('src/klarna'), {recursive: true});
writeFileSync(
  path.resolve('src/klarna/timing.ts'),
  `// GENERATED by scripts/build-klarna-vo.mjs — do not edit by hand.\n` +
  `// Source of truth for what lands where: scripts/klarna-edit.mjs.\n\n` +
  `export const FPS = ${FPS};\n` +
  `export const TOTAL_FRAMES = ${totalFrames};\n\n` +
  `export type Move = {push?: number; dx?: number; dy?: number};\n` +
  `export type Num =\n` +
  `  | {kind: 'hook'; text: string; sub: string}\n` +
  `  | {kind: 'chip'; text: string}\n` +
  `  | {kind: 'split'; from: string; to: string; note: string}\n` +
  `  | {kind: 'arrow'; from: string; to: string}\n` +
  `  | {kind: 'alert'; text: string}\n` +
  `  | {kind: 'locked'; text: string; sub: string}\n` +
  `  | {kind: 'sum'; text: string}\n` +
  `  | {kind: 'cracked'; text: string};\n\n` +
  `export type Shot = {\n` +
  `  id: string;\n  still: number;\n  from: number;\n  durationInFrames: number;\n` +
  `  speech: [number, number];\n  move: Move;\n  cold: boolean;\n  figureY: number;\n` +
  `  cap: string;\n  num: Num | null;\n};\n\n` +
  `export const SHOTS: Shot[] = ${JSON.stringify(timing, null, 2)};\n`
);

rmSync(TMP, {recursive: true, force: true});
console.log(`voiceover  → ../media/klarna-vo.m4a`);
console.log(`timing     → src/klarna/timing.ts`);
console.log(`duration   ${total.toFixed(2)}s  (${totalFrames} frames @ ${FPS}fps)`);
