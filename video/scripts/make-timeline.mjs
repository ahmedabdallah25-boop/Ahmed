// Builds src/pension/timeline.ts from the scene pack + the forced alignment.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';

const FPS = 30;
const here = (p) => new URL(p, import.meta.url);
const scenes = JSON.parse(readFileSync(here('./scenes.json'), 'utf8'));
const aligned = JSON.parse(readFileSync(here('./aligned.json'), 'utf8'));
const pack = readFileSync(here('../../pension-scene-pack.txt'), 'utf8');

const script = pack.split(/VOICEOVER — full script[^\n]*\n/)[1].split(/\nTAG NOTES:/)[0]
  .split('\n').filter((l) => l.trim() && !/^=+$/.test(l.trim()));
if (script.length !== 46 || scenes.length !== 46 || aligned.length !== 46)
  throw new Error(`expected 46 each, got ${script.length}/${scenes.length}/${aligned.length}`);

// Still 15 is a second take of scene 13's basket (herringbone weave where the
// pack asks for cross-hatch) and belongs to no scene. Everything from scene 15
// therefore sits one file later than its scene number.
const SPARE = 15;
const stillFor = (n) => (n < SPARE ? n : n + 1);

const clean = (s) => (s && s !== '(none)' ? s.replace(/\s+/g, ' ').trim() : '');

const out = scenes.map((s, i) => {
  const a = aligned[i];
  const line = script[i];
  const tag = (line.match(/^\[(\w+)\]/) || [, ''])[1];
  const step = (line.match(/^(One|Two|Three)\./) || [, ''])[1];
  return {
    n: s.n,
    still: String(stillFor(s.n)).padStart(2, '0') + '.jpeg',
    from: Math.round(a.start * FPS),
    durationInFrames: Math.max(1, Math.round(a.end * FPS) - Math.round(a.start * FPS)),
    cap1: clean(s.cap1),
    cap2: clean(s.cap2),
    vo: clean(s.n === 46 ? script[i] : s.vo),
    tag,
    step: step ? {One: 1, Two: 2, Three: 3}[step] : 0,
    estimated: a.estimated === true,
  };
});

// Contiguity is what keeps a still on screen for exactly its line.
for (let i = 1; i < out.length; i++) {
  const prevEnd = out[i - 1].from + out[i - 1].durationInFrames;
  if (prevEnd !== out[i].from) out[i - 1].durationInFrames += out[i].from - prevEnd;
}
const totalFrames = out.at(-1).from + out.at(-1).durationInFrames;

mkdirSync(here('../src/pension/'), {recursive: true});
writeFileSync(here('../src/pension/timeline.ts'),
`// GENERATED by scripts/make-timeline.mjs — do not edit by hand.
// Timings come from forced alignment of public/vo-pension.mp3 against the
// scene pack's script (scripts/force-align.py), not from the pack's designed
// timings, which total 196s against a 135.4s recording.
export type Scene = {
  n: number; still: string; from: number; durationInFrames: number;
  cap1: string; cap2: string; vo: string; tag: string; step: number; estimated: boolean;
};

export const FPS = ${FPS};
export const TOTAL_FRAMES = ${totalFrames};
export const SCENES: Scene[] = ${JSON.stringify(out, null, 2)};
`);

console.log(`${out.length} scenes, ${totalFrames} frames (${(totalFrames / FPS).toFixed(2)}s)`);
console.log(`stills used: ${out[0].still} .. ${out.at(-1).still}, spare = ${String(SPARE).padStart(2, '0')}.jpeg`);
console.log(`steps tagged: ${out.filter((s) => s.step).map((s) => `S${s.n}=${s.step}`).join(' ')}`);
console.log(`shortest ${Math.min(...out.map((s) => s.durationInFrames)) / FPS}s  longest ${Math.max(...out.map((s) => s.durationInFrames)) / FPS}s`);
