// Writes src/parents/timeline.ts from the retimed plan.
//
// Supersedes the pack-timed generator this build started with: the read exists
// now, so the pack's designed timecodes are no longer the best information
// available about when a shot should be on screen, and keeping two generators
// that can disagree about the same film is worse than having one.
import {readFileSync, writeFileSync, mkdirSync, existsSync} from 'node:fs';

const here = (p) => new URL(p, import.meta.url).pathname;
const plan = JSON.parse(readFileSync(here('./parents-timeline-vo.json'), 'utf8'));
const shots = JSON.parse(readFileSync(here('./parents-shots.json'), 'utf8'));
const byId = new Map(shots.map((s) => [s.id, s]));
const FPS = plan.fps;

// Section 03 of the pack. The Arabic itself is carried through from the CSV
// rather than retyped here — retyping Quranic text into a build script is the
// error the pack calls its highest-risk item.
const CARD_TEXT = {
  C1: ['WA-QADA RABBUKA', 'And your Lord has decreed'],
  C2: ['WA BIL-WALIDAYNI IHSANA', 'and to parents, good treatment'],
  C3: ["WAHNAN 'ALA WAHN", 'weakness upon weakness'],
  C4: ['WA LI-WALIDAYKA', '...and to your parents'],
  C5: ['UFF', 'a breath of irritation'],
  C6: ['QAWLAN KARIMA', 'a noble word'],
  C7: ["BIRR / 'UQUQ", 'expansive goodness / the cut'],
  C8: ["WA SAHIBHUMA MA'RUFA", 'and keep company with them with kindness'],
  C9: ['RABBI-RHAMHUMA KAMA RABBAYANI SAGHIRA', 'as they raised me when I was small'],
};

// The move each event makes across its still. A still gets a slow push; a
// re-frame gets the move the pack wrote for it, read off the CSV's own prose so
// the two cannot disagree. The pack's ceiling is ~4% of frame width per second;
// every move here is a fixed total travel, an order of magnitude inside it.
const move = (shot) => {
  if (shot.kind !== 'reframe') return {kind: 'push', from: 1.0, to: 1.06};
  const p = shot.prompt.toLowerCase();
  if (/widen|pull back/.test(p)) return {kind: 'widen', from: 1.34, to: 1.0};
  if (/lateral (pan|drift)/.test(p)) return {kind: 'lateral', from: 1.14, to: 1.14};
  if (/hold on|hold and/.test(p)) return {kind: 'hold', from: 1.06, to: 1.12};
  return {kind: 'push', from: 1.06, to: 1.4};
};

const events = plan.events.map((e) => {
  const shot = byId.get(e.id);
  const m = e.kind === 'card' ? {kind: 'hold', from: 1, to: 1.03} : move(shot);
  const asset = e.asset;
  return {
    id: e.id,
    kind: e.kind,
    chapter: e.chapter,
    from: Math.round(e.from * FPS),
    durationInFrames: Math.max(1, Math.round(e.dur * FPS)),
    asset: e.kind === 'card' ? null : asset,
    present: e.kind === 'card' || (asset ? existsSync(here(`../public/parents/${asset}`)) : false),
    parent: e.rfParent || null,
    move: m.kind,
    scaleFrom: m.from,
    scaleTo: m.to,
    arabic: e.kind === 'card' ? shot.prompt.replace(/[★[].*$/u, '').trim() : '',
    translit: e.kind === 'card' ? CARD_TEXT[e.id][0] : '',
    meaning: e.kind === 'card' ? CARD_TEXT[e.id][1] : '',
    split: e.id === 'C7',
    note: e.kind === 'card' ? '' : shot.prompt.slice(0, 120),
  };
});

// Contiguity: a still holds until the next event starts, so rounding to frames
// can never open a one-frame hole in the picture.
for (let i = 1; i < events.length; i++)
  events[i - 1].durationInFrames = events[i].from - events[i - 1].from;
const totalFrames = events.at(-1).from + events.at(-1).durationInFrames;

mkdirSync(here('../src/parents/'), {recursive: true});
writeFileSync(here('../src/parents/timeline.ts'),
`// GENERATED by scripts/write-parents-timeline.mjs — do not edit by hand.
// Timings come from the recorded read: every chapter boundary is where the
// voice actually crosses it (scripts/align-by-clip.py), and shots inside a
// chapter hold the pack's designed proportions across that measured span.
export type Event = {
  id: string; kind: 'still' | 'reframe' | 'card'; chapter: string;
  from: number; durationInFrames: number; asset: string | null; present: boolean;
  parent: string | null; move: string; scaleFrom: number; scaleTo: number;
  arabic: string; translit: string; meaning: string; split: boolean; note: string;
};

export const FPS = ${FPS};
export const TOTAL_FRAMES = ${totalFrames};
export const VO = 'vo-parents.mp3';
export const EVENTS: Event[] = ${JSON.stringify(events, null, 2)};
`);

const secs = totalFrames / FPS;
const missing = events.filter((e) => !e.present);
console.log(`${events.length} events, ${totalFrames} frames (${Math.floor(secs / 60)}:${String(Math.round(secs % 60)).padStart(2, '0')})`);
console.log(`shortest ${(Math.min(...events.map((e) => e.durationInFrames)) / FPS).toFixed(1)}s  ` +
  `longest ${(Math.max(...events.map((e) => e.durationInFrames)) / FPS).toFixed(1)}s`);
if (missing.length)
  console.log(`${missing.length} events have no artwork and render as a slate: ${missing.map((e) => e.id).join(' ')}`);
