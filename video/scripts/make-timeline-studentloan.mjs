// Builds src/studentloan/timeline.ts from the parsed pack + the forced
// alignment of public/vo-student-loan.mp3.
//
// Kept separate from make-timeline.mjs for the same reason the parser is: this
// pack carries two caption lines per scene and no spare still, so the
// scene->still mapping is the identity rather than pension's offset-by-one.
import {readFileSync, writeFileSync, mkdirSync, existsSync} from 'node:fs';

const FPS = 30;
const here = (p) => new URL(p, import.meta.url).pathname;

const scenes = JSON.parse(readFileSync(here('./student-loan-scenes.json'), 'utf8'));
const aligned = JSON.parse(readFileSync(here('./aligned-studentloan.json'), 'utf8'));

if (scenes.length !== 46 || aligned.length !== 46)
  throw new Error(`expected 46 each, got ${scenes.length}/${aligned.length}`);

// Where the art's subject actually starts in each still, measured by
// measure-headroom.py once the stills are on disk. They are not on disk here —
// the container that generated them cannot reach the CDN — so the band falls
// back to a single conservative value for every scene. That is a real loss:
// on the pension pack the measured headroom ranged from 330px to 1424px, and
// a fixed band either puts type on the art or wastes the frame. Re-run
// `npm run headroom:studentloan` after ingesting and rebuild.
const HEADROOM = here('./headroom-studentloan.json');
const headroom = existsSync(HEADROOM) ? JSON.parse(readFileSync(HEADROOM, 'utf8')) : null;
const FALLBACK_BAND = 600;

const clean = (s) => (s && s !== '(none)' ? s.replace(/\s+/g, ' ').trim() : '');

const STEP = {One: 1, Two: 2, Three: 3};

const out = scenes.map((s, i) => {
  const a = aligned[i];
  const still = String(s.n).padStart(2, '0') + '.jpeg';
  const measured = headroom?.[still]?.canvasY;
  // The two-minute check's numbered steps. Matched after the performance tag
  // is stripped — scene 39 reads "[calm] One. Find two published numbers".
  const spoken = s.vo.replace(/\[\w+\]\s*/g, '');
  const step = STEP[(spoken.match(/^(One|Two|Three)\./) || [, ''])[1]] || 0;
  return {
    n: s.n,
    still,
    from: Math.round(a.start * FPS),
    durationInFrames: Math.max(1, Math.round(a.end * FPS) - Math.round(a.start * FPS)),
    cap1: clean(s.caption1),
    cap2: clean(s.caption2),
    vo: clean(s.vo),
    tag: (s.vo.match(/\[(\w+)\]/) || [, ''])[1],
    // 40px clear of where the subject actually starts. The floor must stay
    // BELOW the tightest real measurement or it overrides the thing it exists
    // to protect and puts type on the art.
    capBottom: measured
      ? Math.round(Math.min(980, Math.max(240, measured - 40)))
      : FALLBACK_BAND,
    capMeasured: Boolean(measured),
    step,
    estimated: a.estimated === true,
  };
});

// Hold scene 1 from frame 0 so the video never opens on blank ground.
if (out[0].from > 0) {
  out[0].durationInFrames += out[0].from;
  out[0].from = 0;
}

// Contiguity is what keeps a still on screen for exactly its line.
for (let i = 1; i < out.length; i++) {
  const prevEnd = out[i - 1].from + out[i - 1].durationInFrames;
  if (prevEnd !== out[i].from) out[i - 1].durationInFrames += out[i].from - prevEnd;
}
const totalFrames = out.at(-1).from + out.at(-1).durationInFrames;

mkdirSync(here('../src/studentloan/'), {recursive: true});
writeFileSync(here('../src/studentloan/timeline.ts'),
`// GENERATED by scripts/make-timeline-studentloan.mjs — do not edit by hand.
// Timings come from forced alignment of public/vo-student-loan.mp3 against the
// pack's own scene lines, not from the pack's designed timings, which total
// 196s against a ${(totalFrames / FPS).toFixed(2)}s read.
export type Scene = {
  n: number; still: string; from: number; durationInFrames: number;
  cap1: string; cap2: string; vo: string; tag: string; capBottom: number;
  capMeasured: boolean; step: number; estimated: boolean;
};

export const FPS = ${FPS};
export const TOTAL_FRAMES = ${totalFrames};
export const SCENES: Scene[] = ${JSON.stringify(out, null, 2)};
`);

const secs = totalFrames / FPS;
console.log(`${out.length} scenes, ${totalFrames} frames (${secs.toFixed(2)}s)`);
console.log(`shortest ${(Math.min(...out.map((s) => s.durationInFrames)) / FPS).toFixed(2)}s  ` +
  `longest ${(Math.max(...out.map((s) => s.durationInFrames)) / FPS).toFixed(2)}s`);
console.log(`caption band: ${headroom ? 'measured per scene' : `UNMEASURED — flat ${FALLBACK_BAND}px on all 46`}`);

// Rule 0a puts the strongest reveal at ~40% of runtime. Report where the cuts
// actually fall rather than trusting the pack's figure, which was computed
// against the designed timecodes.
const at = (pct) => {
  const t = secs * pct / 100;
  return out.find((s) => s.from / FPS <= t && (s.from + s.durationInFrames) / FPS > t) || out.at(-1);
};
console.log(`retention checkpoints: ` +
  [20, 30, 40, 50, 60].map((p) => `${p}%=S${at(p).n}`).join('  '));

// The timeline is written either way — the file has to exist for the project to
// typecheck — but an unmeasured band is not something to render on by accident.
// On the pension pack the real headroom ran from 330px to 1424px, so a flat
// fallback puts type on the art in some scenes and wastes half the frame in
// others. Fail loudly instead, and make the override deliberate.
if (!headroom) {
  console.error(
    '\nERROR: caption bands are NOT measured.\n' +
    '  Ingest the stills into public/studentloan, then:\n' +
    '    npm run headroom:studentloan && npm run timeline:studentloan\n' +
    '  To build anyway (previews, typechecking): ALLOW_UNMEASURED_BANDS=1',
  );
  if (process.env.ALLOW_UNMEASURED_BANDS !== '1') process.exit(1);
}
